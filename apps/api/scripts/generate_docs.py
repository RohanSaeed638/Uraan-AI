def web_routes() -> None:
    app_dir = REPO / "apps" / "web" / "app"
    rows = []

    for file in sorted(app_dir.rglob("*")):
        if file.name not in ("page.tsx", "route.ts", "route.tsx", "sitemap.ts", "robots.ts", "manifest.ts", "opengraph-image.tsx"):
            continue

        parts = [p for p in file.relative_to(app_dir).parent.parts if not (p.startswith("(") and p.endswith(")"))]
        groups = [p.strip("()") for p in file.relative_to(app_dir).parent.parts if p.startswith("(") and p.endswith(")")]
        path = "/" + "/".join(parts)

        if file.name in ("sitemap.ts", "robots.ts", "manifest.ts", "opengraph-image.tsx"):
            path = {"sitemap.ts": "/sitemap.xml", "robots.ts": "/robots.txt", "manifest.ts": "/manifest.webmanifest", "opengraph-image.tsx": "/opengraph-image"}[file.name]
            kind = "generated"
        else:
            kind = "page" if file.name == "page.tsx" else "handler"

        area = "signed in" if "app" in groups else "sign-in screens" if "auth" in groups else "public" if "site" in groups or path == "/" else "other"

        if path.startswith("/admin"):
            area = "admin"

        rows.append((path, kind, area, str(file.relative_to(REPO)).replace("\\", "/")))

    lines = [
        "# Web app routes",
        "",
        f"{len(rows)} routes in `apps/web/app/` (Next.js App Router). Folders in brackets are values taken from the address "
        "(`[id]`); folders in parentheses group files without changing the address. "
        "Pages in the *signed in* group redirect to `/login` when there is no session; *admin* pages also need an admin account.",
        "",
        "| Address | Kind | Who can open it | File |",
        "|---|---|---|---|",
    ]

    for path, kind, area, file in sorted(rows):
        lines.append(f"| `{path}` | {kind} | {area} | `{file}` |")

    write("web-routes.md", "\n".join(lines))


