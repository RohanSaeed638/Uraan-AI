"""Writes the reference pages of the documentation from the code itself, so they cannot drift from it.

    python scripts/generate_docs.py

Writes, under docs/reference/:
    api.md             every endpoint and data shape (from the app's OpenAPI description)
    database.md        every table, column, key and index (from the SQLAlchemy models)
    configuration.md   every setting of the API and the web app (from config.py and the .env.example files)
    web-routes.md      every page of the web app (from the folders under apps/web/app)

The guides in docs/ (architecture, user guide, ...) are written by hand and link to these.
Re-run this after changing an endpoint, a model or a setting.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
sys.path.insert(0, str(ROOT))

OUT = REPO / "docs" / "reference"
OUT.mkdir(parents=True, exist_ok=True)

NOTE = "<!-- Generated by apps/api/scripts/generate_docs.py. Do not edit by hand; change the code and run it again. -->\n"


def write(name: str, text: str) -> None:
    (OUT / name).write_text(NOTE + text.rstrip() + "\n", encoding="utf-8")
    print("wrote", OUT / name)


def cell(value) -> str:
    """Text safe inside a Markdown table cell."""
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


# ---- API reference ---------------------------------------------------------------------------------------------------


def schema_type(schema) -> str:
    if not schema or schema is True:
        return "any"

    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]

    if "anyOf" in schema:
        parts = [schema_type(s) for s in schema["anyOf"]]
        return " or ".join(dict.fromkeys(parts))

    if "enum" in schema:
        return " / ".join(f'`{v}`' for v in schema["enum"])

    kind = schema.get("type", "any")

    if kind == "array":
        return f"list of {schema_type(schema.get('items', {}))}"

    if kind == "object" and "additionalProperties" in schema:
        return f"map of {schema_type(schema['additionalProperties'])}"

    fmt = schema.get("format")

    return f"{kind} ({fmt})" if fmt else kind


def api_reference() -> None:
    import json

    spec = json.loads((ROOT / "openapi.json").read_text(encoding="utf-8"))
    paths = spec["paths"]
    schemas = spec.get("components", {}).get("schemas", {})
    by_tag: dict[str, list] = defaultdict(list)

    for path, methods in paths.items():
        for method, op in methods.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue

            by_tag[(op.get("tags") or ["Other"])[0]].append((path, method.upper(), op))

    total = sum(len(v) for v in by_tag.values())
    lines = [
        "# API reference",
        "",
        f"{total} operations on {len(paths)} paths, from `apps/api/openapi.json` (the same description the running API serves at `/docs` and `/openapi.json`).",
        "",
        "## Conventions",
        "",
        "- **Base address:** every endpoint is under `/api/v1`. `GET /health` and `GET /health/ready` (which also checks the database) are at the root.",
        "- **Authentication:** `Authorization: Bearer <Supabase access token>`. Endpoints marked *public* need no token; `/admin/*` also needs an admin account (otherwise `403`).",
        "- **Errors** have one shape: `detail`, `message`, `code` (such as `RATE_LIMIT_001`), `error_code` (the message as lowercase words, used by the web app to translate it) and `request_id`. Every response also carries `X-Request-ID`.",
        "- **Rate limits** return `429` with `Retry-After`. Defaults: anonymous 50/hour, signed in 500/hour, AI chat 100/day, roadmap generation 10/day.",
        "- **Long jobs** (roadmap generation, rebuild, adapt, lesson writing) answer `202` at once; poll `GET /roadmaps/{id}/status` or the task's lessons.",
        "- **Validation errors** are `422` with the field in `detail`.",
        "",
        "## Contents",
        "",
    ]

    for tag in sorted(by_tag):
        anchor = re.sub(r"[^a-z0-9]+", "-", tag.lower()).strip("-")
        lines.append(f"- [{tag}](#{anchor}) ({len(by_tag[tag])})")

    lines.append("- [Data shapes](#data-shapes)")
    lines.append("")

    for tag in sorted(by_tag):
        lines += [f"## {tag}", "", "| Method | Path | What it does | Access |", "|---|---|---|---|"]

        for path, method, op in sorted(by_tag[tag], key=lambda item: (item[0], item[1])):
            summary = op.get("summary", "").strip()
            description = (op.get("description") or "").strip().split("\n\n")[0]
            access = "token" if op.get("security") else "public"

            if path.startswith("/api/v1/admin"):
                access = "admin"

            lines.append(f"| `{method}` | `{path}` | {cell(description or summary)} | {access} |")

        lines.append("")

        for path, method, op in sorted(by_tag[tag], key=lambda item: (item[0], item[1])):
            details = []
            params = [p for p in op.get("parameters", []) if p.get("in") in ("query", "path")]

            if params:
                details.append("Parameters: " + ", ".join(
                    f"`{p['name']}` ({p['in']}{', required' if p.get('required') else ''}: {schema_type(p.get('schema', {}))})"
                    for p in params
                ))

            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")

            if body:
                details.append(f"Body: `{schema_type(body)}`")

            replies = []

            for code, response in op.get("responses", {}).items():
                if code.startswith("2"):
                    content = response.get("content", {}).get("application/json", {}).get("schema")
                    replies.append(f"`{code}`" + (f" `{schema_type(content)}`" if content else ""))

            if replies:
                details.append("Returns: " + ", ".join(replies))

            if details:
                lines.append(f"- `{method} {path}`: " + "; ".join(details))

        lines.append("")

    lines += ["## Data shapes", "", "Every request and response shape, with its fields.", ""]

    for name in sorted(schemas):
        schema = schemas[name]
        props = schema.get("properties", {})

        if not props:
            if "enum" in schema:
                lines += [f"### {name}", "", "One of: " + ", ".join(f"`{v}`" for v in schema["enum"]), ""]
            continue

        required = set(schema.get("required", []))
        lines += [f"### {name}", "", "| Field | Type | Required |", "|---|---|---|"]

        for field, definition in props.items():
            lines.append(f"| `{field}` | {cell(schema_type(definition))} | {'yes' if field in required else 'no'} |")

        lines.append("")

    write("api.md", "\n".join(lines))


