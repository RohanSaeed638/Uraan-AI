def database_reference() -> None:
    import app.models  # noqa: F401  (registers every table)
    from app.db.session import Base

    registry = {mapper.local_table.name: mapper.class_ for mapper in Base.registry.mappers if mapper.local_table is not None}
    tables = list(Base.metadata.sorted_tables)
    lines = [
        "# Database reference",
        "",
        f"{len(tables)} tables in the `public` schema of the Supabase Postgres database, from the SQLAlchemy models in `apps/api/app/models/`.",
        "Migrations are in `apps/api/migrations/versions/` (Alembic). Sign-in accounts live in Supabase's own `auth.users`; "
        "`profiles.auth_user_id` points at them (not as a database foreign key).",
        "",
        "**Row Level Security is enabled on every table** with no public policies, so the browser key can read and write nothing; "
        "the API connects as the table owner. `apps/api/tests/test_rls.py` fails if a table is missing it.",
        "",
        "## Tables",
        "",
        "| Table | What it holds |",
        "|---|---|",
    ]

    def purpose(table) -> str:
        cls = registry.get(table.name)
        doc = (cls.__doc__ or "").strip().split("\n\n")[0].replace("\n", " ") if cls else ""

        return doc

    for table in tables:
        lines.append(f"| [`{table.name}`](#{table.name}) | {cell(purpose(table)) or '(see the model)'} |")

    lines.append("")

    for table in tables:
        lines += [f"## {table.name}", ""]

        if purpose(table):
            lines += [purpose(table), ""]

        lines += ["| Column | Type | Null | Default | Notes |", "|---|---|---|---|---|"]
        unique_columns = {
            column.name
            for constraint in table.constraints
            if constraint.__class__.__name__ == "UniqueConstraint" and len(constraint.columns) == 1
            for column in constraint.columns
        }

        for column in table.columns:
            notes = []

            if column.primary_key:
                notes.append("primary key")

            for fk in column.foreign_keys:
                ondelete = f", on delete {fk.ondelete.lower()}" if fk.ondelete else ""
                notes.append(f"references `{fk.column.table.name}`{ondelete}")

            if column.unique or column.name in unique_columns:
                notes.append("unique")

            if column.index:
                notes.append("indexed")

            default = ""

            if column.server_default is not None:
                default = str(getattr(column.server_default.arg, "text", column.server_default.arg))
            elif column.default is not None and getattr(column.default, "is_scalar", False):
                default = repr(column.default.arg)
            elif column.default is not None:
                default = "set by the application"

            lines.append(
                f"| `{column.name}` | {cell(column.type)} | {'yes' if column.nullable else 'no'} | {cell(default)} | {cell(', '.join(notes))} |"
            )

        extras = []

        for constraint in table.constraints:
            kind = constraint.__class__.__name__

            if kind == "UniqueConstraint" and len(constraint.columns) > 1:
                extras.append(f"unique together: {', '.join(f'`{c.name}`' for c in constraint.columns)}")
            elif kind == "CheckConstraint":
                extras.append(f"check: `{constraint.sqltext}`")

        for index in table.indexes:
            if len(index.columns) > 1:
                extras.append(f"index on {', '.join(f'`{c.name}`' for c in index.columns)}")

        if extras:
            lines += ["", "Also: " + "; ".join(extras) + "."]

        lines.append("")

    write("database.md", "\n".join(lines))


