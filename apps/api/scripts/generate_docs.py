FIELD = re.compile(r"^    ([A-Z][A-Z0-9_]+)\s*:\s*([^=\n]+?)\s*(?:=\s*(.+))?$")
ENV_LINE = re.compile(r"^#?\s*([A-Z][A-Z0-9_]+)=(.*)$")


def comments_and_fields(path: Path, pattern: re.Pattern, comment_prefix: str):
    """Yields (name, extra, comment) for each setting, using the comment lines just above it."""
    buffer: list[str] = []

    for raw in path.read_text(encoding="utf-8").splitlines():
        stripped = raw.strip()

        if stripped.startswith(comment_prefix) and not pattern.match(raw if comment_prefix != "#" else raw):
            buffer.append(stripped.lstrip("#").strip())
            continue

        match = pattern.match(raw)

        if match:
            yield match, " ".join(b for b in buffer if b)
            buffer = []
        elif not stripped:
            buffer = [] if not stripped.startswith("#") else buffer
        else:
            buffer = []


def configuration_reference() -> None:
    lines = [
        "# Configuration reference",
        "",
        "Settings are environment variables. The API reads `apps/api/.env` (or the host's variables); the web app reads `apps/web/.env`. "
        "Copy `apps/api/.env.example` and `apps/web/.env.example` to start. A setting with no default is **required**.",
        "",
        "## API (`apps/api`)",
        "",
        "| Variable | Type | Default | What it does |",
        "|---|---|---|---|",
    ]

    config = ROOT / "app" / "core" / "config.py"
    buffer: list[str] = []
    seen: list[str] = []

    for raw in config.read_text(encoding="utf-8").splitlines():
        stripped = raw.strip()

        if stripped.startswith("#"):
            buffer.append(stripped.lstrip("#").strip())
            continue

        match = FIELD.match(raw)

        if match and "Field(" not in raw:
            name, kind, default = match.group(1), match.group(2).strip(), (match.group(3) or "").strip()

            if name not in API_SETTINGS:
                raise SystemExit(f"Setting {name} has no description: add it to API_SETTINGS in scripts/generate_docs.py")

            seen.append(name)
            lines.append(
                f"| `{name}` | `{cell(kind)}` | {('`' + cell(default) + '`') if default else '**required**'} | {cell(API_SETTINGS[name])} |"
            )
            buffer = []
        elif "CORS_ORIGINS_RAW" in raw and "CORS_ORIGINS" not in seen:
            seen.append("CORS_ORIGINS")
            lines.append(f"| `CORS_ORIGINS` | `str` | the local web address and the project's own sites | {cell(API_SETTINGS['CORS_ORIGINS'])} |")
            buffer = []
        elif stripped:
            buffer = [] if not stripped.startswith(("def ", "@", "model_config", "class ")) else []
        else:
            buffer = []

    lines += [
        "",
        "Which settings turn on optional features:",
        "",
        "- AI: at least one of `OPENAI_API_KEY`, `GEMINI_API_KEY`, `ANTHROPIC_API_KEY` (providers are tried in the order of `AI_PROVIDERS`).",
        "- Email: `RESEND_API_KEY` and `EMAIL_FROM`. Without a key no email is sent (`EMAIL_OUTBOX_DIR` writes emails to files for development).",
        "- Browser push: `VAPID_PUBLIC_KEY` and `VAPID_PRIVATE_KEY` (make them with `python scripts/generate_vapid_keys.py`).",
        "- Monitoring: `SENTRY_DSN`, `POSTHOG_API_KEY` (each does nothing until set).",
        "- Admin portal: `ADMIN_EMAILS`.",
        "",
        "## Web app (`apps/web`)",
        "",
        "Variables starting `NEXT_PUBLIC_` are visible in the browser and are fixed when the app is built: change one, rebuild.",
        "",
        "| Variable | What it does |",
        "|---|---|",
    ]

    buffer = []

    for raw in (REPO / "apps" / "web" / ".env.example").read_text(encoding="utf-8").splitlines():
        stripped = raw.strip()
        match = ENV_LINE.match(stripped)

        if match and (not stripped.startswith("#") or re.match(r"^#\s*[A-Z][A-Z0-9_]+=", stripped)):
            name = match.group(1)

            if name not in WEB_SETTINGS:
                raise SystemExit(f"Web setting {name} has no description: add it to WEB_SETTINGS in scripts/generate_docs.py")

            optional = stripped.startswith("#")
            lines.append(f"| `{name}` | {cell(WEB_SETTINGS[name])}{' (optional)' if optional else ''} |")
            buffer = []
        elif stripped.startswith("#"):
            buffer.append(stripped.lstrip("#").strip())
        else:
            buffer = []

    lines.append("| `NEXT_OUTPUT` | " + cell(WEB_SETTINGS["NEXT_OUTPUT"]) + " |")

    write("configuration.md", "\n".join(lines))


